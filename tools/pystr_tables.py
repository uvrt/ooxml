"""The range tables of ``ooxml_base::pystr`` (crates/ooxml-base/src/pystr/tables.rs): every
code point each of Python's ``str`` predicates reads as true, as sorted inclusive ranges.

    python3.12 tools/pystr_tables.py
        Writes the tables from this CPython's Unicode database. Run it with CPython 3.12
        (Unicode 15.0.0, the version the gates run): it refuses another version.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "crates" / "ooxml-base" / "src" / "pystr" / "tables.rs"

#: The table's name, the predicate, what it is for the doc comment.
TABLES = [
    ("ALPHA", str.isalpha, "`str.isalpha` (general category Lm, Lt, Lu, Ll or Lo)"),
    ("DECIMAL", str.isdecimal, "`str.isdecimal` (Numeric_Type Decimal; `re`'s `\\d`)"),
    ("DIGITS", str.isdigit, "`str.isdigit` (Numeric_Type Decimal or Digit)"),
    ("NUMERIC", str.isnumeric, "`str.isnumeric` (Numeric_Type Decimal, Digit or Numeric)"),
]

#: Ranges per line (the file stays short; rustfmt leaves it as written).
PER_LINE = 4


def ranges(predicate) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for code in range(0x80, sys.maxunicode + 1):
        if 0xD800 <= code <= 0xDFFF or not predicate(chr(code)):
            continue
        if out and out[-1][1] == code - 1:
            out[-1] = (out[-1][0], code)
        else:
            out.append((code, code))
    return out


def table(name: str, predicate, what: str) -> list[str]:
    found = ranges(predicate)
    lines = [f"/// The code points past ASCII CPython 3.12 reads as {what}.", "#[rustfmt::skip]",
             f"pub(super) const {name}: &[(char, char)] = &["]
    for k in range(0, len(found), PER_LINE):
        pairs = " ".join(f"('\\u{{{low:x}}}', '\\u{{{high:x}}}')," for low, high in found[k:k + PER_LINE])
        lines.append(f"    {pairs}")
    return lines + ["];", ""]


def main() -> None:
    if sys.version_info[:2] != (3, 12) or unicodedata.unidata_version != "15.0.0":
        raise SystemExit(f"run with CPython 3.12 (Unicode 15.0.0), not {sys.version.split()[0]} "
                         f"(Unicode {unicodedata.unidata_version})")
    lines = ["//! Generated by tools/pystr_tables.py from CPython 3.12 (Unicode 15.0.0): do not edit.", ""]
    for name, predicate, what in TABLES:
        lines += table(name, predicate, what)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
