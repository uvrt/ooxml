/// `text` folded as `_loose` folds it (after whitespace is collapsed); `None` where a
/// character newer than Unicode 15.0 could make the fold differ from Python's.
pub(crate) fn loose(text: &str) -> Option<String> {
    let newer = |c: char| NEWER.iter().any(|&(low, high)| (low..=high).contains(&c));
    if text.chars().any(newer) {
        return None;
    }
    let mut out = String::with_capacity(text.len());
    for c in text.nfkc() {
        let fold = FOLDS
            .binary_search_by_key(&c, |&(k, _)| k)
            .ok()
            .and_then(|at| FOLDS.get(at));
        match fold {
            Some((_, folded)) => out.push_str(folded),
            None => out.extend(c.to_lowercase()),
        }
    }
    Some(out)
}

