#!/usr/bin/env python3
"""Write ooxml-markdown's table of the characters markdown-it counts as punctuation beside
an emphasis marker: Unicode's general categories P and S (``markdown_it.common.utils.
isPunctChar``: ``unicodedata.category(ch).startswith(("P", "S"))``), as the Python that
runs docx-agent reads them (one source).

``src/punct.rs`` holds the code point ranges, in order.  ``data/entities.tsv`` holds the
HTML5 named character references markdown-it reads (``markdown_it.common.entities``): a
line per name, in sorted order, its characters as hexadecimal code points.

Run from the repository root with the Python docx-agent runs on::

    python crates/ooxml-markdown/data/generate.py           # write the table
    python crates/ooxml-markdown/data/generate.py --check   # exit 1 if it differs
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
TABLE = HERE.parent / "src" / "punct.rs"
ENTITIES = HERE / "entities.tsv"


def ranges() -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for code in range(0x110000):
        inside = unicodedata.category(chr(code)).startswith(("P", "S"))
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            out.append((start, code - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table() -> str:
    lines = [
        "// @generated by crates/ooxml-markdown/data/generate.py -- do not edit",
        f"//! Unicode {unicodedata.unidata_version}'s general categories P and S, as code point ranges",
        "//! (markdown-it's `isPunctChar`).",
        "",
        "/// The ranges, inclusive, in order.",
        "pub(crate) const RANGES: &[(u32, u32)] = &[",
    ]
    pairs = [f"(0x{a:X}, 0x{b:X})," for a, b in ranges()]
    for k in range(0, len(pairs), 6):
        lines.append("    " + " ".join(pairs[k:k + 6]))
    lines.append("];")
    return "\n".join(lines) + "\n"


def entities() -> str:
    from markdown_it.common.entities import entities as names

    lines = ["# @generated by crates/ooxml-markdown/data/generate.py -- do not edit"]
    for name in sorted(names):
        lines.append(name + "\t" + " ".join(f"{ord(c):X}" for c in names[name]))
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    differ = []
    for path, text in ((TABLE, table()), (ENTITIES, entities())):
        if "--check" in argv:
            if not (path.exists() and path.read_text(encoding="utf-8") == text):
                differ.append(path)
        else:
            path.write_text(text, encoding="utf-8")
    for path in differ:
        print(f"{path} differs from what this Python gives")
    return 1 if differ else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
