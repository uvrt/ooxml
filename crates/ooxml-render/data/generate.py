#!/usr/bin/env python3
"""Write ooxml-render's data table from the Python package that holds it (one source).

* ``patterns.tsv``: ``ooxml_common.drawingml.pattern.PRESET_CELLS``, each ``a:pattFill``
  preset's measured 8 x 8 cell -- its name, then its eight rows as two hexadecimal digits
  each (the top row first, the most significant bit the leftmost pixel).

Run from the repository root with ``python/ooxml-common/src`` importable::

    PYTHONPATH=python/ooxml-common/src python crates/ooxml-render/data/generate.py

The table is data, not code: the crate reads it with ``include_str!``.
"""

from __future__ import annotations

from pathlib import Path

from ooxml_common.drawingml.pattern import PRESET_CELLS

HERE = Path(__file__).resolve().parent
HEADER = "# @generated by crates/ooxml-render/data/generate.py -- do not edit\n"


def main() -> None:
    rows = [name + "\t" + " ".join(f"{row:02x}" for row in cells) for name, cells in PRESET_CELLS.items()]
    (HERE / "patterns.tsv").write_text(HEADER + "\n".join(rows) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
