#!/usr/bin/env python3
"""Writes ``crates/ooxml-word-edit/data/child-order.txt`` (test support; phase P2, lane P2a):
the child sequences ooxml-edit's validation checks a part's elements against
(``ooxml_edit.xml.CHILD_ORDER``, with the orders and namespace prefixes docx-agent
adds), as plain data the Rust validation reads with ``include_str!``.

    python crates/ooxml-oracle/python/word_edit_tables.py

Each ``ns`` line is a prefix and its namespace, in the order ``prefixed_name`` looks them up
(the first prefix of a namespace names it); each ``order`` line a parent and its sequence,
steps separated by ``|``, the names of one step (a repeating choice) by spaces.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(Path(__file__).resolve().parent))
# The reference's packages: installed from the frozen commit, or the checkout's (reference_packages.py).
from reference_packages import use_sources  # noqa: E402

use_sources("docx-agent", "ooxml-edit", "ooxml-common")

import docx_agent.validate  # noqa: E402,F401  (adds docx-agent's orders and prefixes)
from ooxml_edit.xml import CHILD_ORDER, NAMESPACES  # noqa: E402

OUT = ROOT / "crates" / "ooxml-word-edit" / "data" / "child-order.txt"


def main() -> int:
    lines = ["# @generated by crates/ooxml-oracle/python/word_edit_tables.py from ooxml-edit's CHILD_ORDER",
             "# and NAMESPACES with docx-agent's additions; do not edit."]
    lines += [f"ns {prefix} {uri}" for prefix, uri in NAMESPACES.items()]
    for parent, steps in CHILD_ORDER.items():
        spelled = " | ".join(step if isinstance(step, str) else " ".join(step) for step in steps)
        lines.append(f"order {parent} = {spelled}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(NAMESPACES)} prefixes, {len(CHILD_ORDER)} orders")
    return 0


if __name__ == "__main__":
    sys.exit(main())
