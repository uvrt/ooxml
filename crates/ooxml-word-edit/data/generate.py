#!/usr/bin/env python3
"""Write ooxml-word-edit's table of Word's built-in style definitions from docx-agent's
measured ones (``docx_agent.edit.builtin_styles.STYLES``: Word 16.106's definitions on a
style's first use; one source).

``builtin-styles.tsv``: a line per style, in the source's order, tab separated: its name,
its type, the styles its ``w:basedOn``, ``w:next`` and ``w:link`` point at (by name; empty
for none), its XML (``{id}`` and the references' places to fill) and, for a list style, the
abstract numbering Word gives it (empty otherwise).

Run from the repository root with docx-agent and its dependencies importable::

    python crates/ooxml-word-edit/data/generate.py           # write the table
    python crates/ooxml-word-edit/data/generate.py --check   # exit 1 if it differs

The table is data, not code: the crate reads it with ``include_str!``.

Since docx-agent 0.2.0 (P4e) the checkout has no ``docx_agent.edit.builtin_styles``: run it with the frozen
reference installed, docx-agent's Python at the commit crates/ooxml-oracle/reference.toml
names (installed as the gates install it: .github/actions/gates-reference, local-gates.sh), or
with ``PYTHONPATH`` pointing into a ``git archive`` of that commit.  The values it reads were
measured from Word and are frozen there; what it writes is unchanged.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TABLE = HERE / "builtin-styles.tsv"
HEADER = "# @generated by crates/ooxml-word-edit/data/generate.py -- do not edit\n"


def table() -> str:
    from docx_agent.edit.builtin_styles import STYLES

    rows = []
    for name, entry in STYLES.items():
        refs = entry["refs"]
        cells = [name, entry["type"], refs.get("basedOn", ""), refs.get("next", ""), refs.get("link", ""),
                 entry["xml"], entry.get("numbering", "")]
        assert not any("\t" in c or "\n" in c for c in cells), name
        rows.append("\t".join(cells))
    return HEADER + "\n".join(rows) + "\n"


def main(argv: list[str]) -> int:
    made = table()
    if "--check" in argv:
        if TABLE.read_text(encoding="utf-8") != made:
            print(f"{TABLE} differs from docx-agent's definitions: run {Path(__file__).name}")
            return 1
        return 0
    TABLE.write_text(made, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
