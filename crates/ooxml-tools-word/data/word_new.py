"""Write ``src/document/new_document/word_new.rs``: the parts of a new blank document that
do not depend on the call, as docx-agent's ``edit/blank.py`` writes them from the values
Word 16.106 made a new blank document of (``edit/word_new.py``, measured by
``tools/e6_probe.py``; ROADMAP.md, "Decisions", 4), and the fixed pieces of the parts that do.

Run from the repository root with docx-agent importable:
``PYTHONPATH=python/docx-agent/src:python/ooxml-edit/src:python/ooxml-common/src python
crates/ooxml-tools-word/data/word_new.py`` (``--check``: exit 1 when the file is not what it
would write; docx-agent's ``tests/test_rust_new.py`` runs it so).
"""
from __future__ import annotations

import sys
from pathlib import Path

from docx_agent.edit import blank
from docx_agent.edit.properties import app_xml

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "document" / "new_document" / "word_new.rs"
MARK = "\u0000"


def literal(text: str) -> str:
    """A Rust string literal of ``text``, split into lines of at most a hundred characters
    at element boundaries (``concat!``)."""
    def escaped(piece: str) -> str:
        return '"' + (piece.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r")
                      .replace("\n", "\\n")) + '"'
    pieces, line = [], ""
    for chunk in text.replace("><", ">\x01<").split("\x01"):
        if line and len(line) + len(chunk) > 96:
            pieces.append(line)
            line = ""
        line += chunk
    pieces.append(line)
    if len(pieces) == 1:
        return escaped(pieces[0])
    return "concat!(\n    " + ",\n    ".join(escaped(p) for p in pieces) + "\n)"


def split(text: str, parts: int) -> list[str]:
    pieces = text.split(MARK)
    assert len(pieces) == parts, (len(pieces), parts)
    return pieces


def generated() -> str:
    """The file's text."""
    styles = split(blank.styles_xml(MARK), 2)
    page = blank.PageDefaults(margin=0, header=0, footer=0, tab_stop=0, column_space=0, hyphenation_zone=None)
    settings = blank.settings_xml(MARK, page, (MARK, MARK))
    head, rest = settings.split('<w:defaultTabStop w:val="0"/>')
    middle, tail = rest.split('<w:themeFontLang w:val="')
    document = blank._root("w:document", blank._DOCUMENT_PREFIXES, blank._IGNORABLE + " wp14")
    consts = [
        ("STYLES_BEFORE_LANGUAGE", "`styles.xml` up to the document defaults' language.", styles[0]),
        ("STYLES_AFTER_LANGUAGE", "`styles.xml` after the document defaults' language.", styles[1]),
        ("SETTINGS_HEAD", "`settings.xml` up to the default tab stop.", head),
        ("SETTINGS_COMPAT", "`settings.xml` from the character spacing control to the math settings.",
         middle),
        ("WEB_SETTINGS", "`webSettings.xml`.", blank.web_settings_xml()),
        ("FONT_TABLE", "`fontTable.xml`.", blank.font_table_xml()),
        ("THEME", "The Office theme (`word/theme/theme1.xml`).", blank.theme_xml()),
        ("APP", "`docProps/app.xml`: a new document's statistics.", app_xml().decode("utf-8")),
        ("DOCUMENT_ROOT", "`document.xml`'s root start tag.", document),
    ]
    _, mapping, decimal, list_tail = split(tail, 4)
    consts += [
        ("SETTINGS_AFTER_LANGUAGE", "`settings.xml` from the theme font language to the decimal symbol.", mapping),
        ("SETTINGS_AFTER_DECIMAL", "`settings.xml` between the decimal symbol and the list separator.", decimal),
        ("SETTINGS_TAIL", "`settings.xml` after the list separator.", list_tail),
    ]
    rows = ["// @generated by crates/ooxml-tools-word/data/word_new.py -- do not edit",
            "//! A new blank document's fixed XML, as docx-agent's `edit/blank.py` writes it from the values",
            "//! Word 16.106 made a new blank document of (`edit/word_new.py`).", ""]
    for name, doc, text in consts:
        rows.append(f"/// {doc}")
        rows.append(f"pub(super) const {name}: &str = {literal(text)};")
        rows.append("")
    return "\n".join(rows)


def main(argv: list[str]) -> int:
    text = generated()
    if "--check" in argv:
        return 0 if OUT.read_text(encoding="utf-8") == text else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
