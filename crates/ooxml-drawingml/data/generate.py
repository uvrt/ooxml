#!/usr/bin/env python3
"""Write ooxml-drawingml's preset geometry table from the Python package that holds it (one
source).

``presets.tsv``: every ECMA-376 preset geometry, as ``ooxml_common.drawingml.presets.PRESETS``
holds it (compiled by pptx2svg's ``tools/derive_preset_geometry.py`` from the
specification's ``presetShapeDefinitions.xml``, SHA-256 pinned there), with its text
rectangle from ``ooxml_common.drawingml.preset_text_rects.PRESET_TEXT_RECTS``. One record a
line, tab separated, in the Python tables' order:

* ``preset`` name, then the text rectangle's ``l t r b`` (guide names or literals);
* ``adj`` name default -- an adjustment and its default (an integer);
* ``gd`` name formula -- a guide, in evaluation order;
* ``path`` fill stroke space -- a path's ``@fill``, ``1``/``0`` for ``@stroke``, and its own
  ``w h`` or ``-``;
* ``cmd`` letter operands... -- a command of the path above (``M L A Q C Z``).

Run from the repository root with ``python/ooxml-common/src`` importable::

    PYTHONPATH=python/ooxml-common/src python crates/ooxml-drawingml/data/generate.py [--check]

``--check`` fails when the file differs from what the tables give. The crate reads the
file with ``include_str!``; the differential (``crates/ooxml-oracle/python/drawingml_diff.py``)
compares every preset with the Python tables too.
"""

from __future__ import annotations

import sys
from pathlib import Path

from ooxml_common.drawingml.preset_text_rects import PRESET_TEXT_RECTS
from ooxml_common.drawingml.presets import PRESETS

HERE = Path(__file__).resolve().parent
TABLE = HERE / "presets.tsv"
HEADER = "# @generated by crates/ooxml-drawingml/data/generate.py -- do not edit\n"


def lines() -> list[str]:
    out = []
    for name, (adjustments, guides, paths) in PRESETS.items():
        out.append("\t".join(["preset", name, *PRESET_TEXT_RECTS[name]]))
        out += ["\t".join(["adj", adjustment, str(default)]) for adjustment, default in adjustments]
        out += ["\t".join(["gd", guide, formula]) for guide, formula in guides]
        for fill, stroke, space, commands in paths:
            written_space = "-" if space is None else f"{space[0]} {space[1]}"
            out.append("\t".join(["path", fill, "1" if stroke else "0", written_space]))
            out += ["\t".join(["cmd", *command]) for command in commands]
    return out


def main() -> int:
    text = HEADER + "\n".join(lines()) + "\n"
    if "--check" in sys.argv[1:]:
        if TABLE.read_text(encoding="utf-8") != text:
            print(f"{TABLE} differs from the Python tables; regenerate it", file=sys.stderr)
            return 1
        return 0
    TABLE.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
