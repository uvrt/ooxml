#!/usr/bin/env python3
"""Write ooxml-style-names' table from ooxml-common's ``stylenames.json`` (one source).

``style-names.tsv``: per measured language a ``language`` line (its code, its region, its
list separator), then a ``name`` line per built-in style (the stored ``w:name`` and the name
that language's Word shows), tab separated, in the JSON's order.

Run from the repository root with ``python/ooxml-common/src`` importable::

    PYTHONPATH=python/ooxml-common/src python crates/ooxml-style-names/data/generate.py

The table is data, not code: the crate reads it with ``include_str!``.
"""

from __future__ import annotations

import json
from importlib import resources
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = "# @generated by crates/ooxml-style-names/data/generate.py -- do not edit\n"


def main() -> None:
    data = json.loads(resources.files("ooxml_common").joinpath("stylenames.json").read_text(encoding="utf-8"))
    rows = []
    for language, entry in data["languages"].items():
        rows.append(f"language\t{language}\t{entry['region']}\t{entry['list_separator']}")
        for stored, display in entry["names"].items():
            assert "\t" not in stored + display and "\n" not in stored + display
            rows.append(f"name\t{stored}\t{display}")
    (HERE / "style-names.tsv").write_text(HEADER + "\n".join(rows) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
